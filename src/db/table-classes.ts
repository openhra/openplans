export const stagingTables = tableClasses
  .filter((table) => table.class === "staging")
  .map((table) => table.name);

export function assertStagingTables(names: readonly string[]): void {
  if (
    new Set(names).size !== names.length ||
    names.some(
      (name) =>
        !tableClasses.some(
          (table) => table.name === name && table.class === "staging",
        ),
    )
  )
    throw new Error("compact target is not a classified staging table");
}
